-- supabase/131_xsports_rooms.sql — X體育 live rooms: fans and one AI
-- commentator chatting during a game (owner, Oct 13: "build the room";
-- ModelXD pays for the room's AI). One room per game per site language,
-- so the commentator speaks one language and each market chats together.
--
--   xsports_room_messages  every message, human or AI. The author's name and
--                          picture are COPIED in when it is sent, so other
--                          people never read the profiles table (its other
--                          columns, country and last-seen time, stay
--                          private; pitfall 16). Readable by anyone,
--                          signed in or not, except hidden rows and the
--                          author's user id (column grants: the page knows
--                          its own messages by the id the send returned).
--                          Supabase Realtime pushes new rows to open rooms.
--   xsports_rooms          one row per room: how far into the plays the AI
--                          has spoken, when it last spoke, and a short lock
--                          so only one open page's request makes it speak.
--   xsports_room_members   whether a person has confirmed the name and
--                          picture shown in rooms (asked at the first
--                          message), and a mute until a time.
--   xsports_room_reports   one report per person per message; enough of
--                          them hide the message.
--
-- Only the server writes (service role). Revoked from public, anon and
-- authenticated by name (pitfalls 15 and 16), SELECT granted back on the
-- messages' public columns only. Additive; safe to re-run.
--
-- Run by hand. Dev and prod share this database.

begin;

create table if not exists public.xsports_room_messages (
  id            bigint generated by default as identity primary key,
  league        text not null check (league ~ '^[a-z0-9_]{2,16}$'),
  game_id       text not null check (length(game_id) between 1 and 32),
  lang          text not null check (lang ~ '^[A-Za-z-]{2,10}$'),
  kind          text not null check (kind in ('human', 'ai')),
  user_id       uuid references auth.users(id) on delete cascade,
  author_name   text not null check (length(author_name) between 1 and 60),
  author_avatar text check (author_avatar is null or length(author_avatar) <= 500),
  content       text not null check (length(content) between 1 and 4000),
  model_name    text,
  reply_to      bigint references public.xsports_room_messages(id) on delete set null,
  hidden        boolean not null default false,
  created_at    timestamptz not null default now()
);

create index if not exists xsports_room_messages_room on public.xsports_room_messages (league, game_id, lang, id desc);
create index if not exists xsports_room_messages_author on public.xsports_room_messages (user_id, created_at desc);

create table if not exists public.xsports_rooms (
  league         text not null,
  game_id        text not null,
  lang           text not null,
  ai_since       text,                 -- last play the AI has spoken about
  ai_last_at     timestamptz,          -- when the AI last spoke
  ai_busy_until  timestamptz,          -- the speaking lock
  ai_lulls       integer not null default 0,
  created_at     timestamptz not null default now(),
  primary key (league, game_id, lang)
);

create table if not exists public.xsports_room_members (
  user_id            uuid primary key references auth.users(id) on delete cascade,
  name_confirmed_at  timestamptz,
  muted_until        timestamptz
);

create table if not exists public.xsports_room_reports (
  message_id  bigint not null references public.xsports_room_messages(id) on delete cascade,
  user_id     uuid not null references auth.users(id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (message_id, user_id)
);

alter table public.xsports_room_messages enable row level security;
alter table public.xsports_rooms enable row level security;
alter table public.xsports_room_members enable row level security;
alter table public.xsports_room_reports enable row level security;

revoke all on public.xsports_room_messages from public, anon, authenticated;
revoke all on public.xsports_rooms from public, anon, authenticated;
revoke all on public.xsports_room_members from public, anon, authenticated;
revoke all on public.xsports_room_reports from public, anon, authenticated;

-- The public columns of a message; never user_id or hidden.
grant select (id, league, game_id, lang, kind, author_name, author_avatar, content, model_name, reply_to, created_at)
  on public.xsports_room_messages to anon, authenticated;

grant all on public.xsports_room_messages to service_role;
grant all on public.xsports_rooms to service_role;
grant all on public.xsports_room_members to service_role;
grant all on public.xsports_room_reports to service_role;

drop policy if exists xsports_room_messages_read on public.xsports_room_messages;
create policy xsports_room_messages_read on public.xsports_room_messages
  for select to anon, authenticated
  using (not hidden);

-- New messages reach open rooms through Supabase Realtime.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'xsports_room_messages') then
    alter publication supabase_realtime add table public.xsports_room_messages;
  end if;
end $$;

commit;

