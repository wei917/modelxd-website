-- supabase/130_xsports_chats.sql — X體育 (XSports) saved chats (owner, Oct 12:
-- "can I have multiple chat for the same game?"). Until now a chat lived in
-- one browser tab's sessionStorage: gone when the tab closed, one per game.
--
--   xsports_chats      one row per chat: whose it is, which league and game
--                      (`game_id` is text because leagues number games
--                      differently: MLB 849820, NBA "0012600012"), the model
--                      last used, how far into the plays the commentator has
--                      been told (`since`), and what it has cost so far. A
--                      user may have any number of chats for the same game.
--   xsports_messages   one row per message, in order (`seq`, one
--                      database-wide number): the viewer's own words, the
--                      commentator's remarks (with the cue it read before
--                      speaking, so the conversation can be rebuilt for the
--                      model), and notes (out of credits, a failed remark).
--                      `after_event` is the last play the viewer had seen,
--                      so the page can weave the messages back between the
--                      plays, which are not stored (the feed has them).
--
-- Access: the same as XTell's memory (126). A user reads only their own
-- chats and messages; only the server writes (service role), after checking
-- the chat is the caller's, so the conversation the model reads is the one
-- the server stored. Both tables are revoked from public, anon and
-- authenticated by name (pitfalls 15 and 16), then SELECT is granted back to
-- authenticated under the owner policy. Deleting a chat, or the account,
-- deletes its messages (cascade). Additive only; safe to re-run.
--
-- Migration 129 is claude/traffic-internal's (site_internal_users).
-- Run by hand. Dev and prod share this database.

begin;

create table if not exists public.xsports_chats (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references auth.users(id) on delete cascade,
  league      text not null default 'mlb' check (league ~ '^[a-z0-9_]{2,16}$'),
  game_id     text not null check (length(game_id) between 1 and 32),
  title       text check (title is null or length(title) <= 200),
  model_id    text,                       -- ai_models id last used
  since       text,                       -- last play the commentator was told about
  spent_usd   numeric not null default 0, -- list cost of every remark, for display
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists xsports_chats_user_recent on public.xsports_chats (user_id, updated_at desc);
create index if not exists xsports_chats_user_game on public.xsports_chats (user_id, league, game_id);

create table if not exists public.xsports_messages (
  seq           bigint generated by default as identity primary key,
  chat_id       uuid not null references public.xsports_chats(id) on delete cascade,
  kind          text not null check (kind in ('viewer', 'remark', 'note')),
  content       text not null check (length(content) <= 20000),
  cue           text check (cue is null or length(cue) <= 8000),  -- a remark: what the model was told
  trigger       text check (trigger is null or trigger in ('open', 'event', 'lull', 'user')),
  after_event   text,                     -- last play the viewer had seen
  model_id      text,                     -- a remark: the ai_models id
  model_name    text,
  input_tokens  integer,
  cost          numeric,                  -- a remark: list cost in USD
  created_at    timestamptz not null default now()
);

create index if not exists xsports_messages_chat on public.xsports_messages (chat_id, seq);

alter table public.xsports_chats enable row level security;
alter table public.xsports_messages enable row level security;

revoke all on public.xsports_chats from public, anon, authenticated;
revoke all on public.xsports_messages from public, anon, authenticated;
grant select on public.xsports_chats to authenticated;
grant select on public.xsports_messages to authenticated;
grant all on public.xsports_chats to service_role;
grant all on public.xsports_messages to service_role;

drop policy if exists xsports_chats_owner_read on public.xsports_chats;
create policy xsports_chats_owner_read on public.xsports_chats
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists xsports_messages_owner_read on public.xsports_messages;
create policy xsports_messages_owner_read on public.xsports_messages
  for select to authenticated
  using (exists (select 1 from public.xsports_chats c where c.id = chat_id and c.user_id = auth.uid()));

commit;

